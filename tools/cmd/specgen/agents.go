package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"strings"

	"birdcage/tools/internal/loopkit"
)

// AGENTS.md is generated from specs/principles.json + loop/policy.json so that the
// rules every agent session loads (CLAUDE.md imports it) never drift from the SSOT.
// 근거 문장(why/evidence)은 넣지 않는다: 세션마다 읽는 고정 접두를 짧고 안정적으로 유지(원칙 A7).

type principleRef struct {
	Type string `json:"type"`
	Ref  string `json:"ref,omitempty"`
}

type principle struct {
	ID         string         `json:"id"`
	Group      string         `json:"group"`
	Rule       string         `json:"rule"`
	Why        string         `json:"why"`
	Evidence   []string       `json:"evidence,omitempty"`
	EnforcedBy []principleRef `json:"enforcedBy"`
	Status     string         `json:"status"`
}

type principlesSpec struct {
	Version int `json:"version"`
	Groups  []struct {
		ID    string `json:"id"`
		Title string `json:"title"`
	} `json:"groups"`
	Principles []principle `json:"principles"`
}

type gate struct {
	ID       string   `json:"id"`
	Level    string   `json:"level"`
	Kind     string   `json:"kind"`
	Cost     string   `json:"cost"`
	What     string   `json:"what"`
	Argv     []string `json:"argv,omitempty"`
	Dir      string   `json:"dir,omitempty"`
	EstSec   float64  `json:"estSec,omitempty"`
	Optional bool     `json:"optional,omitempty"`
}

type agentPolicy struct {
	Budgets struct {
		MaxIterationsPerTask    int `json:"maxIterationsPerTask"`
		MaxIterationMinutes     int `json:"maxIterationMinutes"`
		StallAfterSameSignature int `json:"stallAfterSameSignature"`
	} `json:"budgets"`
	HumanGates []struct {
		Action string `json:"action"`
	} `json:"humanGates"`
	Protected struct {
		Paths []string `json:"paths"`
	} `json:"protected"`
	Sessions struct {
		FreshContextFor []string `json:"freshContextFor"`
		StartupRoutine  []string `json:"startupRoutine"`
	} `json:"sessions"`
	GateLadder []gate `json:"gateLadder"`
	Divergence struct {
		AllowedWhen          []string `json:"allowedWhen"`
		MaxCandidates        int      `json:"maxCandidates"`
		MaxSubagentsPerPulse int      `json:"maxSubagentsPerPulse"`
		MaxTokensPerPulse    int      `json:"maxTokensPerPulse"`
	} `json:"divergence"`
	Models struct {
		Routing []struct {
			Role    string `json:"role"`
			Model   string `json:"model"`
			Context string `json:"context,omitempty"`
		} `json:"routing"`
	} `json:"models"`
	Feedback struct {
		TailLines int `json:"tailLines"`
	} `json:"feedback"`
}

// semanticPrinciples drops why/evidence (rationale) from the hash.
func semanticPrinciples(p principlesSpec) []byte {
	type sp struct {
		ID, Group, Rule, Status string
		EnforcedBy              []principleRef
	}
	var out []sp
	for _, x := range p.Principles {
		out = append(out, sp{x.ID, x.Group, x.Rule, x.Status, x.EnforcedBy})
	}
	b, _ := json.Marshal(struct {
		Groups any
		P      []sp
	}{p.Groups, out})
	return b
}

func loadAgentsInputs(root string) (principlesSpec, agentPolicy, string, error) {
	var ps principlesSpec
	var pol agentPolicy
	v := loopkit.NewValidator(root)
	if err := v.ValidateFile("specs/principles.schema.json", "specs/principles.json"); err != nil {
		return ps, pol, "", err
	}
	if err := v.ValidateFile("loop/schema/policy.schema.json", "loop/policy.json"); err != nil {
		return ps, pol, "", err
	}
	if err := loopkit.ReadJSON(root, "specs/principles.json", &ps); err != nil {
		return ps, pol, "", err
	}
	if err := loopkit.ReadJSON(root, "loop/policy.json", &pol); err != nil {
		return ps, pol, "", err
	}
	polSem, _ := json.Marshal(pol) // agentPolicy has only the fields AGENTS.md renders (no why texts)
	h := sha256.New()
	h.Write(semanticPrinciples(ps))
	h.Write(polSem)
	return ps, pol, "sha256:" + hex.EncodeToString(h.Sum(nil)), nil
}

func agentsMD(ps principlesSpec, pol agentPolicy, hash string) []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	cell := func(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
	w("<!-- Code generated by specgen from specs/principles.json + loop/policy.json; DO NOT EDIT. -->\n")
	w("<!-- semantic-hash: %s -->\n\n", hash)
	w("# Birdcage 에이전트 작업 규칙\n\n")
	w("이 파일은 생성물이다. 규칙을 바꾸려면 `specs/principles.json`(원칙)·`loop/policy.json`(파라미터)을 고치고 `make gen`. ")
	w("근거(why·evidence)는 SSOT에 있다. 지식의 집은 저장소다(loop/, specs/, docs/decisions/premises.json).\n\n")

	w("## 세션\n\n")
	w("- 세션 하나 = 작업(백로그 항목) 하나 = 반복 하나. 새 컨텍스트로 시작하는 세션: %s.\n", strings.Join(pol.Sessions.FreshContextFor, ", "))
	w("- 시작 루틴:\n")
	for i, s := range pol.Sessions.StartupRoutine {
		w("  %d. `%s`\n", i+1, s)
	}
	w("- 반복: `loopctl begin --task T-NNN --kind <kind> --hypothesis \"…\"` → 구현 → `make gates` → `loopctl end --state <상태> --summary … --next …` → 브랜치 커밋.\n")
	w("- 예산: 작업당 %d회, 반복당 %d분. 같은 실패 서명 %d회 → 같은 컨텍스트 재시도 금지(새 세션·발산 펄스·사람).\n\n",
		pol.Budgets.MaxIterationsPerTask, pol.Budgets.MaxIterationMinutes, pol.Budgets.StallAfterSameSignature)

	for _, g := range ps.Groups {
		w("## %s\n\n| ID | 규칙 | 강제 | 상태 |\n|---|---|---|---|\n", g.Title)
		for _, p := range ps.Principles {
			if p.Group != g.ID {
				continue
			}
			var refs []string
			for _, r := range p.EnforcedBy {
				if r.Type == "honor" {
					refs = append(refs, "자율")
					continue
				}
				refs = append(refs, r.Type+":"+r.Ref)
			}
			w("| %s | %s | %s | %s |\n", p.ID, cell(p.Rule), cell(strings.Join(refs, ", ")), p.Status)
		}
		w("\n")
	}

	w("## 게이트 사다리 (`make gates`, 싼 것부터, 앞에서 실패하면 중단)\n\n| 게이트 | 단계 | 비용 | 확인 | 명령 |\n|---|---|---|---|---|\n")
	for _, g := range pol.GateLadder {
		cmd := "—"
		if len(g.Argv) > 0 {
			cmd = "`" + cell(strings.Join(g.Argv, " ")) + "`"
			if g.Dir != "" {
				cmd = "(" + g.Dir + ") " + cmd
			}
		}
		what := g.What
		if g.Optional {
			what += " (선택)"
		}
		w("| %s | %s | %s | %s | %s |\n", g.ID, g.Level, g.Cost, cell(what), cmd)
	}

	w("\n## 사람 게이트 (실행 전에 알리고 승인받는다)\n\n")
	for _, h := range pol.HumanGates {
		w("- `%s`\n", h.Action)
	}
	w("\n## 보호 경로 (구현 세션은 추가만, 수정·삭제는 verifier.change 승인)\n\n")
	for _, p := range pol.Protected.Paths {
		w("- `%s`\n", p)
	}
	w("\n## 발산·모델·피드백\n\n")
	w("- 발산 펄스 허용 조건: %s. 상한: 후보 %d개, 서브에이전트 %d개, 토큰 %d.\n",
		strings.Join(pol.Divergence.AllowedWhen, ", "), pol.Divergence.MaxCandidates, pol.Divergence.MaxSubagentsPerPulse, pol.Divergence.MaxTokensPerPulse)
	var routes []string
	for _, r := range pol.Models.Routing {
		s := r.Role + "→" + r.Model
		if r.Context != "" {
			s += "(" + r.Context + " context)"
		}
		routes = append(routes, s)
	}
	w("- 모델 라우팅: %s.\n", strings.Join(routes, ", "))
	w("- 실패를 모델에 넘길 때: `loopctl brief` (실패 서명 + 마지막 %d줄 + 산출물 경로). 원본 로그를 붙이지 않는다.\n", pol.Feedback.TailLines)
	return b.Bytes()
}
